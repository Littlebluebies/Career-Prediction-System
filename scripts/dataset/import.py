"""Generate the reference seed SQL from the validated processed dataset.

datasets/processed/*.csv + datasets/metadata/*.json
    -> validate.py checks (stop on any failure)
    -> database/seed/reference/NN_<table>.seed.sql   (generated, committed)
    -> loaded by:  scripts/database/seed.sh reference

Why SQL files instead of writing to the database directly:
  * Python stays standard-library only (no database driver, ADR 0010 §6)
  * the exact rows that enter the database are reviewable in Git
  * loading reuses seed.sh (one transaction, ON CONFLICT DO NOTHING)

The output is deterministic: running the script twice gives identical files.
Do not edit the generated files by hand; change the pipeline and re-run.

Run from the repository root:  py -3.13 scripts/dataset/import.py
Standard library only (ADR 0010 §6).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import validate
from common import (CAREER_FAMILIES, DATASET_VERSION, METADATA_DATASETS, SEED_REFERENCE,
                    metadata_path, rel)

HEADER = """-- =============================================================
-- {file} — REFERENCE DATA (ESCO pilot, dataset version {version})
-- GENERATED by scripts/dataset/import.py — do not edit by hand.
-- Source: datasets/processed/ + datasets/metadata/ (ADR 0006, ADR 0010)
-- Loaded by: scripts/database/seed.sh reference
-- =============================================================

"""


def q(value: str | None) -> str:
    """SQL string literal (standard_conforming_strings: only ' needs escaping)."""
    if value is None or value == "":
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def values(rows: list[tuple]) -> str:
    return ",\n".join("    (" + ", ".join(q(v) for v in row) + ")" for row in rows)


def career_family_sql() -> str:
    rows = [(code, name, "Initial candidate career family (DATABASE.md §19)")
            for code, name in CAREER_FAMILIES]
    return ("INSERT INTO career_family (family_code, family_name, description) VALUES\n"
            + values(rows) + "\nON CONFLICT (family_code) DO NOTHING;\n")


def skill_sql(skill, skill_alias) -> str:
    rows = [(s["skill_name"], s["category"], s["description"]) for s in skill]
    aliases = [(a["skill_name"], a["alias"]) for a in skill_alias]
    return ("INSERT INTO skill (skill_name, category, description) VALUES\n"
            + values(rows) + "\nON CONFLICT (skill_name) DO NOTHING;\n\n"
            "INSERT INTO skill_alias (skill_id, alias)\n"
            "SELECT s.skill_id, v.alias\n"
            "FROM (VALUES\n" + values(aliases) + "\n) AS v (skill_name, alias)\n"
            "JOIN skill s ON s.skill_name = v.skill_name\n"
            "ON CONFLICT (alias) DO NOTHING;\n")


def occupation_sql(occ, occ_alias) -> str:
    uri = {o["occupation_name"]: o["source_identifier"] for o in occ}
    rows = [(o["career_family_code"], o["occupation_name"], o["description"],
             o["source"], o["source_identifier"]) for o in occ]
    aliases = [(uri[a["occupation_name"]], a["alias"]) for a in occ_alias]
    # occupations are found again by their ESCO URI (source_identifier), not by name
    return ("INSERT INTO occupation (career_family_id, occupation_name, description, source, source_identifier)\n"
            "SELECT cf.career_family_id, v.occupation_name, v.description, v.source, v.source_identifier\n"
            "FROM (VALUES\n" + values(rows) + "\n) AS v (family_code, occupation_name, description, source, source_identifier)\n"
            "JOIN career_family cf ON cf.family_code = v.family_code\n"
            "ON CONFLICT ON CONSTRAINT uq_occupation DO NOTHING;\n\n"
            "INSERT INTO occupation_alias (occupation_id, alias)\n"
            "SELECT o.occupation_id, v.alias\n"
            "FROM (VALUES\n" + values(aliases) + "\n) AS v (source_identifier, alias)\n"
            "JOIN occupation o ON o.source_identifier = v.source_identifier\n"
            "ON CONFLICT (alias) DO NOTHING;\n")


def occupation_skill_sql(occ, rel_rows) -> str:
    uri = {o["occupation_name"]: o["source_identifier"] for o in occ}
    rows = [(uri[x["occupation_name"]], x["skill_name"], x["source"]) for x in rel_rows]
    # importance and demand are left NULL (ADR 0010 §3)
    return ("INSERT INTO occupation_skill (occupation_id, skill_id, source)\n"
            "SELECT o.occupation_id, s.skill_id, v.source\n"
            "FROM (VALUES\n" + values(rows) + "\n) AS v (source_identifier, skill_name, source)\n"
            "JOIN occupation o ON o.source_identifier = v.source_identifier\n"
            "JOIN skill s ON s.skill_name = v.skill_name\n"
            "ON CONFLICT ON CONSTRAINT uq_occupation_skill DO NOTHING;\n")


def dataset_version_sql() -> str:
    # metadata field -> dataset_version column (ADR 0006 §5)
    rows = []
    for name in METADATA_DATASETS:
        m = json.loads(metadata_path(name).read_text(encoding="utf-8"))
        rows.append("    (" + ", ".join([q(m["dataset_name"]), q(m["version"]), q(m["source"]),
                                         q(m["collection_date"]) + "::timestamptz",
                                         str(int(m["number_of_records"])), q(m["description"])]) + ")")
    return ("INSERT INTO dataset_version (dataset_name, version_name, source_description, collected_at, record_count, description) VALUES\n"
            + ",\n".join(rows) + "\nON CONFLICT ON CONSTRAINT uq_dataset_version DO NOTHING;\n")


def write(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(file=path.name, version=DATASET_VERSION) + body)
    print(f"  wrote {rel(path)}")


def main() -> None:
    print(f"Step 1/2: validate dataset {DATASET_VERSION}")
    data = validate.load()
    if validate.run_checks(data):
        print("Import stopped: fix the failed checks first.", file=sys.stderr)
        sys.exit(1)

    print("\nStep 2/2: generate reference seed SQL")
    # file number = load order: parents before children (foreign keys)
    write(SEED_REFERENCE / "01_career_family.seed.sql", career_family_sql())
    write(SEED_REFERENCE / "02_skill.seed.sql", skill_sql(data["skill"], data["skill_alias"]))
    write(SEED_REFERENCE / "03_occupation.seed.sql", occupation_sql(data["occupation"], data["occupation_alias"]))
    write(SEED_REFERENCE / "04_occupation_skill.seed.sql",
          occupation_skill_sql(data["occupation"], data["occupation_skill"]))
    write(SEED_REFERENCE / "05_dataset_version.seed.sql", dataset_version_sql())
    print("\nDone. Load with: bash scripts/database/seed.sh reference")


if __name__ == "__main__":
    main()
