#!/usr/bin/env bash
# =============================================================
# seed.sh — load seed data into the database
# Sources: DATABASE_MIGRATION_PLAN §42-48, docs/decisions/0003-database-tooling.md §6,
#          docs/decisions/0010-phase-2-reference-data-decisions.md
#
# Usage (after migrate.sh):
#   scripts/database/seed.sh                 # development (default): DEMO / TEST DATA
#   scripts/database/seed.sh reference       # reference: ESCO pilot dataset
#   DB_NAME=career_system_test scripts/database/seed.sh reference
#
# Modes are never mixed in one database (DATABASE_MIGRATION_PLAN §43,
# DATASET_SPEC §56 "Research data separated from seed data"):
# the script stops if the database already holds data of the other mode.
#
# Safe to run many times: every INSERT uses ON CONFLICT DO NOTHING.
# =============================================================
set -euo pipefail
cd "$(dirname "$0")/../.."

MODE="${1:-development}"
DB_NAME="${DB_NAME:-}"
DEMO_SOURCE="DEMO / DEVELOPMENT DATA"

case "$MODE" in
  development)
    SEED_DIR="database/seed/development"
    # Explicit order: parents before children (occupation needs career_family)
    SEED_FILES=()
    for name in major career_family skill occupation; do
      SEED_FILES+=("$SEED_DIR/$name.seed.sql")
    done
    ;;
  reference)
    SEED_DIR="database/seed/reference"
    # Generated by scripts/dataset/import.py; the NN_ prefix is the load order
    shopt -s nullglob
    SEED_FILES=("$SEED_DIR"/[0-9][0-9]_*.seed.sql)
    shopt -u nullglob
    if [ "${#SEED_FILES[@]}" -eq 0 ]; then
      echo "ERROR: no reference seed files. Run: py -3.13 scripts/dataset/import.py" >&2
      exit 1
    fi
    ;;
  *)
    echo "Usage: $0 [development|reference]" >&2
    exit 1
    ;;
esac

psql_db() {
  docker compose exec -T -e TARGET_DB="$DB_NAME" postgres \
    sh -c 'export PGOPTIONS="-c client_min_messages=warning"; exec psql -X -q -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "${TARGET_DB:-$POSTGRES_DB}" "$@"' psql "$@"
}

if ! docker compose exec -T postgres pg_isready -q; then
  echo "ERROR: postgres container is not running or not ready. Run: docker compose up -d postgres" >&2
  exit 1
fi

ready="$(psql_db -tA -c "SELECT to_regclass('career_system.occupation_alias') IS NOT NULL;")"
if [ "$ready" != "t" ]; then
  echo "ERROR: tables not found. Run scripts/database/migrate.sh first." >&2
  exit 1
fi

# --- guard: do not mix DEMO data and reference data ---
has_demo="$(psql_db -tA -c "
  SELECT EXISTS (SELECT 1 FROM career_system.occupation WHERE source = '$DEMO_SOURCE')
      OR EXISTS (SELECT 1 FROM career_system.career_family WHERE description LIKE 'DEMO%')
      OR EXISTS (SELECT 1 FROM career_system.skill WHERE description LIKE 'DEMO%');")"
has_reference="$(psql_db -tA -c "
  SELECT EXISTS (SELECT 1 FROM career_system.dataset_version)
      OR EXISTS (SELECT 1 FROM career_system.occupation WHERE source IS DISTINCT FROM '$DEMO_SOURCE');")"

if [ "$MODE" = "development" ] && [ "$has_reference" = "t" ]; then
  echo "ERROR: database already holds REFERENCE data. Use a fresh database (scripts/database/reset.sh development)." >&2
  exit 1
fi
if [ "$MODE" = "reference" ] && [ "$has_demo" = "t" ]; then
  echo "ERROR: database already holds DEMO / TEST DATA. Use a fresh database (scripts/database/reset.sh reference)." >&2
  exit 1
fi

if [ "$MODE" = "development" ]; then
  for file in "${SEED_FILES[@]}"; do
    echo "Seeding $(basename "$file" .seed.sql) ..."
    {
      echo "SET search_path TO career_system, public;"
      cat "$file"
    } | psql_db --single-transaction
  done
else
  # Reference data is loaded in ONE transaction: all files or nothing
  echo "Seeding reference data: ${SEED_FILES[*]##*/}"
  {
    echo "SET search_path TO career_system, public;"
    cat "${SEED_FILES[@]}"
  } | psql_db --single-transaction
fi

echo "Done. $MODE seed loaded (database: ${DB_NAME:-POSTGRES_DB})"
